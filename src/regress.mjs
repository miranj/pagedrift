/**
 * Visual regression check between two git refs of a project whose site is
 * running locally: captures baseline screenshots at <baseline>, then
 * compares the site at <compare> (the current checkout by default) against
 * them. URIs are collected from the compared ref’s sitemap.
 *
 * As with `git diff`, <baseline>..<compare> compares the two refs directly,
 * and an omitted <compare> means the current checkout.
 *
 * Baseline screenshots are kept per baseline commit and reused by later
 * runs, which only capture pages that don’t have one yet. `fresh` discards
 * them and captures all pages again, eg. after content changes.
 *
 * Refs are checked out in place, so tracked files must have no changes, and
 * the site must be running (on any local server) throughout.
 */

import { execSync } from 'node:child_process';
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { createGit } from './git.mjs';
import { die, say, warn } from './log.mjs';
import { runPlaywright, suiteConfig, writeSpec } from './playwright.mjs';
import { runStateEnvVar, writeRunState } from './run-state.mjs';
import { loadSettings, resolveBaseUrl } from './settings.mjs';
import { collectUris, randomSeed } from './uris.mjs';

export async function regress({
  projectDir,
  configFile,
  range,
  fresh,
  seed,
  playwrightArgs,
}) {
  const git = createGit(projectDir);

  // Arguments and preconditions

  if (range.includes('...')) {
    die(
      `${range} compares against the merge base. Use <baseline>..<compare> to compare the two refs directly.`,
    );
  }
  const [baselineRef, compareRef, ...extra] = range.split('..');
  if (!baselineRef || extra.length) {
    die(`Invalid range: ${range}. Use <baseline> or <baseline>..<compare>.`);
  }

  if (!git.isRepo()) {
    die(`${projectDir} is not in a git repository.`);
  }
  if (!git.isClean()) {
    die('Tracked files have uncommitted changes. Commit or stash them first.');
  }

  const settings = await loadSettings(projectDir, configFile);
  const baseUrl = resolveBaseUrl(settings, projectDir);
  seed ??= settings.seed ?? randomSeed();

  const originalRef = git.currentRef();
  const baselineSha =
    git.resolveCommit(baselineRef) ?? die(`Unknown git ref: ${baselineRef}`);
  const compareSha =
    git.resolveCommit(compareRef || 'HEAD') ??
    die(`Unknown git ref: ${compareRef}`);
  const compareLabel = compareRef || originalRef;

  const siteChanges = git.changedPaths(
    baselineSha,
    compareSha,
    settings.siteStatePaths,
  );
  if (siteChanges.length) {
    warn(
      `${siteChanges.join(', ')} differ between ${baselineRef} and ${compareLabel}, so differences may come from the site’s dependencies, config or database rather than templates.`,
    );
  }

  // Generated files

  const { outputDir } = settings;
  const runDir = join(outputDir, 'run');
  const runStateFile = join(runDir, 'state.json');
  const snapshotDir = join(outputDir, 'baselines', baselineSha);

  mkdirSync(outputDir, { recursive: true });
  writeFileSync(join(outputDir, '.gitignore'), '# Generated by pagedrift\n*\n');
  rmSync(runDir, { recursive: true, force: true });
  mkdirSync(runDir);
  writeSpec(runDir);
  if (fresh) {
    rmSync(snapshotDir, { recursive: true, force: true });
  }

  // The config file may differ between the refs, or not exist at one of
  // them, so a copy is used for the whole run
  const runConfigFile = configFile && join(runDir, basename(configFile));
  if (configFile) {
    copyFileSync(configFile, runConfigFile);
  }

  // Steps

  let onOriginal = true;

  function checkout(ref, sha) {
    say(`Checking out ${ref}`);
    // By SHA, so a branch name like `dev` doesn’t attach to that branch
    git.checkout(sha);
    onOriginal = false;
    runAfterCheckout();
  }

  function restore() {
    if (onOriginal) {
      return;
    }
    say(`Returning to ${originalRef}`);
    git.checkout(originalRef);
    onOriginal = true;
    runAfterCheckout();
  }

  function runAfterCheckout() {
    const command = settings.afterCheckout;
    if (!command) {
      return;
    }
    say(`Running: ${command}`);
    try {
      execSync(command, { cwd: projectDir, stdio: 'inherit' });
    } catch {
      warn('The afterCheckout command failed');
    }
  }

  function runSuite(state, args) {
    writeRunState(runStateFile, {
      projectDir,
      testDir: runDir,
      configFile: runConfigFile,
      baseUrl,
      snapshotDir,
      ...state,
    });

    return runPlaywright(['test', '--config', suiteConfig, ...args], {
      cwd: projectDir,
      env: { [runStateEnvVar]: runStateFile },
    });
  }

  // Main flow

  // Let Ctrl+C stop Playwright, then still return to the original branch
  process.on('SIGINT', () => {});

  let status = 1;
  try {
    if (compareRef) {
      checkout(compareRef, compareSha);
    }

    say(`Collecting URIs from the ${compareLabel} sitemap (--seed=${seed})`);
    const uris = await collectUris(settings, baseUrl, seed);
    say(`${uris.length} URIs collected`);

    checkout(baselineRef, baselineSha);
    say(
      `Capturing baseline screenshots at ${baselineRef}, for pages without one in ${snapshotDir}`,
    );
    // List reporter only: the HTML report is written by the comparison run
    const baselineStatus = runSuite({ uris, capturingBaseline: true }, [
      '--update-snapshots=all',
      '--reporter=list',
      ...playwrightArgs,
    ]);
    if (baselineStatus !== 0) {
      warn(
        'Some baseline captures failed. Those pages will be reported as failures.',
      );
    }

    if (compareRef) {
      checkout(compareRef, compareSha);
    } else {
      restore();
    }
    say(`Comparing ${compareLabel} against ${baselineRef}`);
    // Missing baselines fail, rather than being captured from <compare>
    status = runSuite({ uris, capturingBaseline: false }, [
      '--update-snapshots=none',
      ...playwrightArgs,
    ]);

    say('View the report with: npx pagedrift report');
  } finally {
    restore();
  }

  return status;
}
